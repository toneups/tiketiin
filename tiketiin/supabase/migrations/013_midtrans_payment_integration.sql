BEGIN;

-- 1. Tabel pemeriksaan pembayaran Midtrans
CREATE TABLE IF NOT EXISTS public.midtrans_payment_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id INTEGER NOT NULL UNIQUE
        REFERENCES public.orders(id) ON DELETE RESTRICT,

    transaction_id TEXT UNIQUE,
    transaction_status TEXT NOT NULL,
    gross_amount NUMERIC(15, 2),

    reason TEXT NOT NULL,

    review_status TEXT NOT NULL DEFAULT 'OPEN'
        CHECK (review_status IN ('OPEN', 'RESOLVED')),

    payload JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at TIMESTAMPTZ
);

-- 2. Index untuk pencarian kasus pemeriksaan
CREATE INDEX IF NOT EXISTS idx_midtrans_reviews_status
ON public.midtrans_payment_reviews(review_status);

CREATE INDEX IF NOT EXISTS idx_midtrans_reviews_created
ON public.midtrans_payment_reviews(created_at DESC);

-- 3. Aktifkan RLS
ALTER TABLE public.midtrans_payment_reviews
ENABLE ROW LEVEL SECURITY;

-- 4. Batasi akses langsung dari client
REVOKE ALL ON TABLE public.midtrans_payment_reviews
FROM PUBLIC, anon, authenticated;

-- Backend tepercaya dapat mengakses tabel
GRANT SELECT, INSERT, UPDATE
ON TABLE public.midtrans_payment_reviews
TO service_role;

GRANT USAGE, SELECT
ON SEQUENCE public.midtrans_payment_reviews_id_seq
TO service_role;

COMMIT;
